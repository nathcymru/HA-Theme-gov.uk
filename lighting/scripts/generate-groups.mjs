// Generates lighting/ha/govuk_lighting_groups.yaml: one Home Assistant light group per room.
// The card's Settings button opens Home Assistant's own more-info dialog for these groups, so the
// native brightness slider, colour wheel and temperature control act on the whole room.
// Membership comes from lighting/ha/area-lights.json (a snapshot of the area registry).
import { readFileSync, writeFileSync } from 'node:fs';

const rooms = JSON.parse(readFileSync(new URL('../rooms.json', import.meta.url), 'utf8')).rooms;
const areaLights = JSON.parse(readFileSync(new URL('../ha/area-lights.json', import.meta.url), 'utf8'));
const q = (s) => JSON.stringify(s);

const withLights = rooms.filter((r) => (areaLights[r.area] ?? []).length > 0);
const groups = withLights.map((r) => {
  const members = (areaLights[r.area] ?? []).filter((e) => !(r.exclude ?? []).includes(e));
  return `  - platform: group
    name: ${q(`Lights ${r.id[0].toUpperCase()}${r.id.slice(1)}`)}
    unique_id: ${q(`govuk_lights_group_${r.id}`)}
    entities:
${members.map((e) => `      - ${e}`).join('\n')}
`;
}).join('');

writeFileSync(new URL('../ha/govuk_lighting_groups.yaml', import.meta.url),
  `# GENERATED by lighting/scripts/generate-groups.mjs from lighting/ha/area-lights.json. Do not edit.\n# Copy to /homeassistant/packages/. Entity ids are light.govuk_lights_<room>.\nlight:\n${groups}`);
